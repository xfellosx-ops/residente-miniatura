def rot(qs):
    """Rota letras (orden cíclico, sin cambiar textos) para que la correcta caiga en E, B, D, A, C, E, …"""
    out = []
    for i, (cont, enun, ops, key, exps, perla, refs) in enumerate(qs):
        L = "ABCDE"; target = "EBDAC"[i % 5]; k = (L.index(target) - L.index(key)) % 5
        nl = {x: L[(L.index(x) + k) % 5] for x in L}  # letra vieja → nueva
        o2 = dict(sorted((nl[x], ops[x]) for x in L)); e2 = dict(sorted((nl[x], exps[x]) for x in L))
        out.append((cont, enun, o2, target, e2, perla, refs))
    return out

